/**
 * ★ 2026-11-12（P0-0）：疑问词单列出来 —— 只有它需要"宾语尾巴"例外。
 *
 * 「打开相册是什么意思」里的"什么"是**在问这句话什么意思**（不排）；
 * 「打开菜谱看看有什么」里的"什么"是**宾语**（排）。
 * 以前它们都在 `META` 里，于是 `LOOK_TAIL` 一绕守卫就把两者一起放行。
 */
const ASK_WORD = /什么|啥|哪个|哪儿|哪里|多少/;

/**
 * ★ 2026-11-12（P0-0）：**宾语尾巴**（"打开菜谱看看有什么 / 看看里面有什么"）。
 *
 * 这不是问句，是"让你去看看那里头有什么"。`blocked()` 会把它当问句挡掉，
 * 所以 `phone-gate` 用 `guardReason(text, { allowGoalTail: true })` 单独开这一个口子。
 */
const OBJECT_TAIL = /(?:看看|看一下|瞧瞧|瞅瞅|翻翻|读读|看|读|翻)(?:[^\s，。；;！!？?]{0,6}?)(?:里面|里头|里|上)?(?:有什么|有啥|有些什么|是什么|都有什么)/;

/** 去掉句首句尾的标点，但保留中间的字。 */
function clean(text) {
  return String(text || '')
    .replace(/^[\s，。！？!?、~～…：:]+/, '')
    .replace(/[\s，。！？!?、~～…：:]+$/, '')
    .trim();
}

/**
 * 是不是问句/否定/抱怨（在**剥前缀之前**判断，避免把"能不能"误当问句）。
 *
 * @param {string} raw
 * @param {{allowGoalTail?:boolean}} [opts]
 *   `allowGoalTail`：把"看看有什么/里面有什么"当**宾语**而不是问句（只有 `phone-gate` 用）。
 */
function blocked(raw, { allowGoalTail = false } = {}) {
  if (raw.length > MAX_LEN) return true;
  const goalTail = !!allowGoalTail && OBJECT_TAIL.test(raw);
  if (!goalTail && /(吗|么|呢|嘛)\s*[？?]?$/.test(raw)) return true;
  if (/(?:没有|没)\s*[？?]?$/.test(raw)) return true;
  if (/[？?]\s*$/.test(raw)) return true;
  if (!goalTail && ASK_WORD.test(raw)) return true;
  return META.some((rx) => rx.test(raw));
}

/** 剥掉称呼/礼貌前缀，得到"动作本体"。 */
function bare(raw) {
  let s = clean(raw);
  for (let i = 0; i < 4; i++) {
    const next = s.replace(PREFIX, '').trim();
    if (next === s) break;
    s = next;
  }
  return s;
}

/** "第一条 / 第2个 / 那条" → 第几条（认不出就当第 1 条）。 */
const CN_NUM = { 一: 1, 二: 2, 两: 2, 三: 3, 四: 4, 五: 5, 六: 6, 七: 7, 八: 8, 九: 9, 十: 10 };
function nthOf(s) {
  const m = String(s || '').match(/\d+|[一二两三四五六七八九十]/);
  if (!m) return 1;
  return /^\d+$/.test(m[0]) ? Number(m[0]) : (CN_NUM[m[0]] || 1);
}

