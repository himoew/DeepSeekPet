/** 这个动作词前面是不是刚被否掉/在转述（"先别往下滑" / "你说往下翻"）。 */
function negatedAt(clause, index) {
  const before = clause.slice(Math.max(0, index - 4), index);
  return SCAN_NEG.test(before) || SCAN_QUOTE.test(before);
}

/**
 * 在一个小句里扫一个动作。扫不到 / 被守卫拦下 → `null`。
 * @returns {{kind:string, goal:string, dir?:string, raw:string}|null}
 */
function scanClause(clause) {
  const s = String(clause || '');
  if (!s) return null;
  if (SCAN_NOT.test(s) || SCAN_ASK.test(s) || SCAN_PAST.test(s) || SCAN_FAIL.test(s)) return null;
  /**
   * ★ 2026-11-12（P0-0）：**陈述 / 假设 / 未来也不排**。
   *
   * 这两条是真机日志（不是理论风险）：
   *   · 11-11 23:02「学你的，你写日记**也**这样」→ 被扫成「写日记」；
   *   · 11-12 21:33「你**刚**返回卡了，重新看看桌面就能看到了」→ 被扫成「返回」（由 `SCAN_PAST` 挡）。
   * 守卫只写一份，`LOOK_TAIL` 与 `phone-gate` 都走 `guardReason()`。
   */
  if (STATEMENT.test(s) || HYPOTHETICAL.test(s) || FUTURE.test(s)) return null;
  for (const act of SCAN_ACTIONS) {
    const rx = new RegExp(act.rx.source, 'g');
    let m = rx.exec(s);
    while (m) {
      if (!negatedAt(s, m.index)) {
        const goal = typeof act.goal === 'function' ? act.goal(m) : act.goal;
        if (goal) {
          return {
            kind: act.kind,
            goal,
            ...(act.dir ? { dir: act.dir } : {}),
            raw: s,
            via: 'scan',
          };
        }
      }
      m = rx.exec(s);
    }
  }
  return null;
}

/**
 * 认一句"主人让她在手机上做的事"。
 *
 * 先按标点切成小句再逐句认：「你现在往下滑，你现在在网页里面。」的第一句就是指令，
 * 后面那半句只是说明 —— 不切的话整句永远匹配不上（真机上他原话就是这样）。
 *
 * ★ 2026-11-08：切句符补 `…` `～` `、`（语音转写里 `……` 极多，
 * 「…不要搜图片**……你点网页**」以前整段被当成一句、被 `别/不要` 否掉）。
 * 每句先试**整句规则**（准），再试**扫动作**（宽，但有守卫）。
 *
 * ★ 2026-11-08（R-A 的根）：**他的复合句以前只认第一个小句**。
 *
 * 「打开浏览器，搜小肥鱼表情包，然后找自己喜欢的网址点进去挑」→ 旧版只返回
 * `{kind:'open', goal:'打开浏览器'}`，后面两小句**直接丢掉**；再叠加"他的算"，
 * 她那句更完整的 `[手机:打开浏览器搜小肥鱼表情包]` 被摘掉。
 * 现在 `ownerCommands()` 把**每一小句能认出的动作都收下来**（最多 3 段），
 * `ownerCommand()` 把它们用「，」连成一句话交给 `phone-agent.splitGoal()` 依次做。
 *
 * @param {string} text 主人这一句原话
 * @returns {{kind:string, goal:string, dir?:string, keyword?:string, raw:string, steps?:string[]}|null}
 */
/**
 * ★ 2026-11-12：**同一句里"回桌面 + 看某个 App"是两个动作**（真机 21:51）。
 *
 * 他说「现在试试去手机桌面**看我给你写的日记**，这次应该没问题了」——
 * 按标点切只有一个从句，`parseClause()` 认出"桌面"就返回了，后半句"看日记"整段丢掉；
 * 她只好写 `[手机:回桌面]`，然后嘴上说「桌面上点开日记本，我看了」（其实没开）。
 * 这条尾巴只挂在本句已经认出 home/back 的时候，避免和"打开浏览器搜…"这类重复。
 */
const LOOK_TAIL = /(?:看看|瞧瞧|读读|翻翻|看|读|翻|打开)(?:我给你写的|你写给我的|你写的给我|我写的|给你的|你的|那个|一下|下)*(日记本|日记|相册|图库|浏览器|设置|哔哩哔哩|b站|文件|应用商店)/i;

/**
 * ★ 2026-11-12（P0-0，最急的一条）：**这条尾巴以前完全不设防。**
 *
 * 21:55 加 `LOOK_TAIL` 时只想着"整句认不出也要收一件"，忘了它绕过了 `blocked()` 和全部 `SCAN_*`。
 * 用当前模块跑 17 句，**16 句**会被排成"打开X"：
 *   「别打开相册」「先别打开日记本」「刚才你打开相册了吗」「你说打开日记本」
 *   「我让你打开相册」「为什么打开相册这么慢」「如果打开相册会怎样」「你明天打开相册看看」…
 * 这不是理论风险：他会插队打断她自己那一场，跑 20 步，然后回他一句他没让做的事。
 *
 * 修法（最小、最稳）：**把全部守卫收成一个纯函数**，`LOOK_TAIL`、`phone-gate`、
 * 以后任何"补一句"的地方都只调它 —— 判"是不是"的规则只写一份（和 `phone-play.cjs` 的经验一致）。
 *
 * @param {string} raw 他这一句（或一个小句）
 * @param {{allowGoalTail?:boolean}} [opts] 见 `blocked()`
 * @returns {string} 拦下的原因（空串 = 放行）
 */
function guardReason(raw, opts = {}) {
  const s = String(raw || '');
  if (!s.trim()) return 'empty';
  if (s.length > MAX_LEN) return 'too-long';
  if (blocked(s, opts)) return 'blocked';
  if (SCAN_ASK.test(s)) return 'ask';
  if (SCAN_PAST.test(s)) return 'past';
  if (SCAN_NOT.test(s)) return 'self';
  if (SCAN_FAIL.test(s)) return 'complain';
  if (STATEMENT.test(s)) return 'statement';
  if (HYPOTHETICAL.test(s)) return 'hypothetical';
  if (FUTURE.test(s)) return 'future';
  return '';
}

/** 按标点切小句（`ownerCommands()` / `phone-gate` 共用；纯函数，不碰手机）。 */
function clauses(text) {
  const rawAll = clean(text);
  if (!rawAll) return [];
  const list = rawAll
    .split(/[，,。；;！!？?、…～~\n]+/)
    .map((x) => clean(x))
    .filter(Boolean);
  return list.length ? list : [rawAll];
}

function ownerCommands(text) {
  const rawAll = clean(text);
  if (!rawAll) return [];
  const list = clauses(rawAll);
  const out = [];
  for (const raw of list) {
    const c = parseClause(raw);
    /**
     * ★ 2026-11-08 夜：**同一件事不重复收**。
     * 真机 23:16「那你现在返回首页，返回桌面，然后…」→ 两个小句都是"回桌面"，
     * 收成「回桌面，回桌面」，日志和任务都很难看（还会白排一步）。
     */
    if (c && !out.some((x) => x.kind === c.kind && x.goal === c.goal)) out.push(c);
    /**
     * ★ 2026-11-12：**"先回桌面，再看 X"** —— 一句里两个动作。
     * 只在 ①本句没认出任何动作（`c` 为空，真机 21:51 就是这种：
     * 「现在试试去手机桌面看我给你写的日记」整句一条规则都不匹配）
     * 或 ②已经认出 home/back 时补；补出来的那件单独排在它后面。
     *
     * ★ 2026-11-12（P0-0）：**补之前先过 `guardReason()`**（原来这里什么都不看，
     * 于是"别打开相册/刚才你打开相册了吗/你说打开日记本"全被排成了一次真实任务）。
     */
    if ((!c || c.kind === 'home' || c.kind === 'back') && !guardReason(raw)) {
      const m = LOOK_TAIL.exec(raw);
      if (m) {
        const goal = `打开${m[1]}，看看里面有什么`;
        const covered = c && String(c.goal).includes(m[1]);
        if (!covered && !out.some((x) => x.goal === goal)) out.push({ kind: 'launch', goal, raw, via: 'look' });
      }
    }
    /** 一段话里最多认 3 件（再多就不像一句指挥了，也超出队列预算）。 */
    if (out.length >= 3) break;
  }
  return out;
}

/** 认**一个小句**。整句规则优先（准），认不出再扫动作（宽，但有守卫）。 */
function parseClause(raw) {
  const bareRaw = bare(raw).replace(/\s+/g, '');
  if (!bareRaw) return null;
  if (READ_ANY.test(bareRaw)) return { kind: 'read', goal: '读这一页', raw };
  if (!blocked(raw)) {
    const g = bareRaw;
    for (const rule of RULES) {
      const m = rule.rx.exec(g);
      if (!m) continue;
      const goal = typeof rule.goal === 'function' ? rule.goal(m) : rule.goal;
      if (!goal) continue;
      return {
        kind: rule.kind,
        goal,
        ...(rule.dir ? { dir: rule.dir } : {}),
        ...(rule.kind === 'search' ? { keyword: goal.replace(/^搜索/, '') } : {}),
        raw,
      };
    }
  }
  /** 整句认不出 → 在小句里扫动作（守卫在 `scanClause()` 里）。 */
  const scanned = scanClause(bareRaw);
  return scanned ? { ...scanned, raw } : null;
}

/**
 * 一句原话 → **一件事**（多小句就用「，」连起来，交给 `phone-agent.splitGoal()` 拆段）。
 */
function ownerCommand(text) {
  const list = ownerCommands(text);
  if (!list.length) return null;
  if (list.length === 1) return list[0];
  const steps = list.map((c) => c.goal);
  return {
    kind: list[0].kind,
    goal: steps.join('，'),
    steps,
    raw: list.map((c) => c.raw).join('，'),
    via: 'multi',
  };
}

/** 只判"像不像"，给处境提示用（不执行）。 */
function looksLikePhoneAsk(text) {
  return !!ownerCommand(text);
}

/**
 * ★ 2026-11-07：**他是不是在问"你现在看到什么"**（要现场读一屏）。
 *
 * 真机（21:57）：「你给我描述一下你现在看到的是什么」→ 她张口就说"加速器、下载、官网"，
 * 而那三个词来自 24 分钟前的旧页。她不是故意编：回灌只给了 `res.summary`，
 * 这一轮**没有人**去读屏。这条判断就是那个入口 —— 只有他明确问"看到什么"时才读一屏，
 * 不自动读、不每轮读（用户红线：别每轮把屏幕塞进提示词）。
 *
 * 认：
 *   · 有"屏幕/这一屏/这一页/画面"这类**指示物**，或者"你看到/你看见"；
 *   · 并且是在问内容（什么/啥/描述/说说/念/读/长什么样）。
 * 不认（都是真机上出现过的说法）：
 *   · 过去：「刚才看到什么」「你刚才看到的是不是…」
 *   · 评价/猜测：「你觉得这一页怎么样」「为什么看到这个」
 *   · 确认：「你确定看到的是小飞鱼加速器？」「你看到了吗」
 */
const SEE_ANY = /(屏幕|这一屏|这页|这一页|当前页|界面|画面|看到|看见)/;
const SEE_ASK = /(描述|说说|讲讲|念一下|读一下|是什么|是啥|有什么|啥|什么|长什么样|有哪些|都有什么|显示)/;
const SEE_NOT = /(刚才|刚刚|上次|之前|昨天|以前|为什么|为啥|怎么|觉得|感觉|是不是|有没有|看到了吗|看见了吗|记得|确定|吗)/;
function asksAboutScreen(text) {
  const t = clean(text);
  if (!t || t.length > 40) return false;
  if (SEE_NOT.test(t)) return false;
  return SEE_ANY.test(t) && SEE_ASK.test(t);
}

